  // メイン生成関数
  static generateCommandsFromInput(inputText: string): AutoGeneratedButtonConfig[] {
    console.log('🔍 DynamicCommandGenerator入力分析開始:', inputText);
    const analysis = this.analyzeInput(inputText);
    console.log('📊 分析結果:', {
      frameworks: analysis.frameworks,
      technologies: analysis.technologies,
      actions: analysis.actions,
      features: analysis.features,
      complexity: analysis.complexity,
      category: analysis.category
    });

    let commands: AutoGeneratedButtonConfig[] = [];

    // フレームワーク別コマンド生成
    if (analysis.frameworks.includes('flask')) {
      console.log('✅ Flask検出 -> Flaskコマンド生成実行');
      commands = commands.concat(this.generateFlaskCommands(analysis));
    }

    if (analysis.frameworks.includes('react')) {
      commands = commands.concat(this.generateReactCommands(analysis));
    }

    if (analysis.frameworks.includes('next')) {
      console.log('✅ Next.js検出 -> Next.jsコマンド生成実行');
      commands = commands.concat(this.generateNextCommands(analysis));
    }

    if (analysis.frameworks.includes('django')) {
      console.log('✅ Django検出 -> Djangoコマンド生成実行');
      commands = commands.concat(this.generateDjangoCommands(analysis));
    }

    if (analysis.frameworks.includes('tensorflow')) {
      console.log('✅ TensorFlow検出 -> TensorFlowコマンド生成実行');
      commands = commands.concat(this.generateTensorFlowCommands(analysis));
    }

    // カテゴリ別コマンド生成
    if (analysis.category === 'data_visualization') {
      commands = commands.concat(this.generateDataVisualizationCommands(analysis));
    }

    // 曖昧入力への推論処理
    if (commands.length === 0) {
      const inferences = this.inferFromAmbiguousInput(inputText);
      console.log('🤔 曖昧入力検出 -> 推論実行:', inferences);

      if (inferences.includes('flask')) {
        console.log('💡 Flask推論適用');
        const flaskAnalysis = { ...analysis, frameworks: ['flask'] };
        commands = commands.concat(this.generateFlaskCommands(flaskAnalysis));
      }

      if (inferences.includes('matplotlib')) {
        console.log('💡 データ可視化推論適用');
        const vizAnalysis = { ...analysis, category: 'data_visualization' };
        commands = commands.concat(this.generateDataVisualizationCommands(vizAnalysis));
      }
    }

    // 汎用コマンド追加
    if (commands.length === 0) {
      commands.push({
        id: `generic_help_${Date.now()}`,
        title: '❓ ヘルプ・ガイダンス',
        description: '入力内容に基づく推奨アクションを表示',
        category: 'general',
        command: `echo "入力内容: ${inputText.substring(0, 50)}..." && echo "検出された要素:" && echo "- フレームワーク: ${analysis.frameworks.join(', ') || 'なし'}" && echo "- 技術: ${analysis.technologies.join(', ') || 'なし'}" && echo "- アクション: ${analysis.actions.join(', ') || 'なし'}"`,
        execution_type: 'bash',
        button_config: {
          type: 'info',
          icon: '❓',
          color: '#666666',
          gradient: ['#666666', '#555555'],
          priority: 999
        },
        local_metrics: {
          metrics: { confidence_score: 0.70 }
        },
        created_at: new Date().toISOString(),
        source: 'dynamic_generator'
      });
    }

    return commands;
  }

