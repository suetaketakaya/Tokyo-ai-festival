  // 入力テキストからカテゴリを推定
  static inferCategory(inputText: string): string {
    const analysis = this.analyzeInput(inputText);
    return analysis.category;
  }

  // 曖昧入力推論強化
  static inferFromAmbiguousInput(inputText: string): string[] {
    const text = inputText.toLowerCase();
    const inferences = [];

    // Web関連推論
    if ((text.includes('web') || text.includes('サイト') || text.includes('簡単')) &&
        !text.includes('react') && !text.includes('vue')) {
      inferences.push('flask');
    }

    // 学習目的推論
    if (text.includes('勉強') || text.includes('学習') || text.includes('練習')) {
      inferences.push('flask');
    }

    // データ分析推論
    if (text.includes('データ') && text.includes('分析')) {
      inferences.push('matplotlib');
    }

    return inferences;
  }

  // 信頼度スコア計算
  static calculateConfidenceScore(inputText: string, commandType: string): number {
    const analysis = this.analyzeInput(inputText);
    let score = 0.5; // ベーススコア

    // フレームワーク一致
    if (commandType.includes('flask') && analysis.frameworks.includes('flask')) score += 0.3;
    if (commandType.includes('react') && analysis.frameworks.includes('react')) score += 0.3;
    if (commandType.includes('next') && analysis.frameworks.includes('next')) score += 0.3;
    if (commandType.includes('django') && analysis.frameworks.includes('django')) score += 0.3;
    if (commandType.includes('tensorflow') && analysis.frameworks.includes('tensorflow')) score += 0.3;

    // アクション一致
    if (commandType.includes('install') && analysis.actions.includes('install')) score += 0.2;
    if (commandType.includes('start') && analysis.actions.includes('start')) score += 0.2;
    if (commandType.includes('create') && analysis.actions.includes('create')) score += 0.2;

    return Math.min(score, 1.0);
  }
